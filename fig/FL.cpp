#include <bits/stdc++>
using namespace std;

int main() {
    cout << "=== FOR LOOP BASICO ===" << endl;
    
    // Contagem de 0 a 4
    for (int i = 0; i < 5; i++) {
        cout << "Iteracao " << i << endl;
    }
    
    cout << "\n=== CONTAGEM DE 1 A 10 ===" << endl;
    for (int i = 1; i <= 10; i++) {
        cout << i << " ";
    }
    cout << endl;
    
    return 0;
}